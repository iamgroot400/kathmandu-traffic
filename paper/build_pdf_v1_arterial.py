def core_numbers():
    rows = list(csv.DictReader(open(RESULTS / "comparison.partial.csv", encoding="utf-8")))
    by = {}
    for r in rows:
        by.setdefault(r["config"], {})[int(r["seed"])] = r
    return by, by["fixed_time"]


def interaction_term(by, base):
    adaptive, pricing, combined = by["adaptive"], by["pricing"], by["adaptive_pricing"]
    shared = sorted(set(base) & set(adaptive) & set(pricing) & set(combined))
    terms = []
    for s in shared:
        b = float(base[s]["delay_s"])
        a, p, c = float(adaptive[s]["delay_s"]), float(pricing[s]["delay_s"]), float(combined[s]["delay_s"])
        terms.append((c - b) - ((a - b) + (p - b)))
    mean_i, ci_i = ci95(terms)
    neg = sum(1 for t in terms if t < 0)
    return mean_i, ci_i, neg, len(terms)


def capacity_sweep_numbers():
    """Per (capacity, lever), paired % change vs fixed_time at that capacity."""
    rows = list(csv.DictReader(open(RESULTS / "capacity_sweep.csv", encoding="utf-8")))
    by = {}
    for r in rows:
        by.setdefault(r["capacity"], {}).setdefault(r["lever"], {})[int(r["seed"])] = r
    out = {}
    for cap, levers in by.items():
        base = levers.get("fixed_time", {})
        for lever in ["adaptive", "pricing", "adaptive_pricing"]:
            runs = levers.get(lever, {})
            shared = sorted(set(base) & set(runs))
            if len(shared) < 2:
                continue
            diffs = [float(runs[s]["delay_s"]) - float(base[s]["delay_s"]) for s in shared]
            rels = [d / float(base[s]["delay_s"]) * 100 for d, s in zip(diffs, shared)]
            mean_r, ci_r = ci95(rels)
            neg = sum(1 for d in diffs if d < 0)
            comp = [(float(runs[s]["completed"]) - float(base[s]["completed"])) * 100 for s in shared]
            mean_c, ci_c = ci95(comp)
            out[(cap, lever)] = (mean_r, ci_r, neg, len(shared), mean_c, ci_c)
        out[(cap, "base_completion")] = statistics.mean(float(r["completed"]) for r in base.values())
        out[(cap, "base_full")] = (sum(float(r["completed"]) >= 0.999 for r in base.values()), len(base))
    return out


def future_numbers(fname, label):
    """Completion under projected demand; delay is not comparable when most trips never finish."""
    by = {}
    for r in csv.DictReader(open(RESULTS / fname, encoding="utf-8")):
        by.setdefault(r["config"], {})[int(r["seed"])] = r
    base, proj = by["baseline"], by[label]
    shared = sorted(set(base) & set(proj))
    mean_c, ci_c = ci95([float(proj[s]["completed"]) for s in shared])
    worst = max(float(proj[s]["completed"]) for s in shared)
    return mean_c * 100, ci_c * 100, worst * 100, len(shared)


def followup_numbers():
    """Paired % delay change, b vs a, from the audit follow-ups (E10). clean = both arms complete."""
    def load(name):
        by = {}
        for r in csv.DictReader(open(RESULTS / name, encoding="utf-8")):
            by.setdefault(r["config"], {})[int(r["seed"])] = r
        return by
    f, extra, core = load("followups.partial.csv"), load("extra.partial.csv"), load("comparison.partial.csv")

    def pair(a, b, clean):
        seeds = sorted(set(a) & set(b))
        if clean:
            seeds = [s for s in seeds if float(a[s]["completed"]) >= 0.999 and float(b[s]["completed"]) >= 0.999]
        rel = [(float(b[s]["delay_s"]) - float(a[s]["delay_s"])) / float(a[s]["delay_s"]) * 100 for s in seeds]
        m, ci = ci95(rel)
        return m, ci, sum(x < 0 for x in rel), len(seeds)

    trips = lambda name: float(next(iter(f[name].values()))["trips"])
    return {
        "uniform": pair(extra["baseline"], f["uniform_cut"], True),
        "decent_vs_uniform": pair(f["uniform_cut"], extra["decentralized"], True),
        "stag4500": pair(extra["baseline"], f["staggered_4500"], True),
        "pricing_el": pair(core["fixed_time"], f["pricing_elastic"], False),
        "combined_el": pair(core["fixed_time"], f["combined_elastic"], False),
        "kept": trips("pricing_elastic") / float(next(csv.DictReader(open(RESULTS / "baseline_trips.csv")))["trips"]) * 100,
    }


def geh_numbers():
    """Pass count, n, and model volume as a share of observed, from checks/geh_jica2012.py."""
    rows = list(csv.DictReader(open(RESULTS / "geh_jica2012.csv", encoding="utf-8")))
    n_pass = sum(1 for r in rows if r["pass"] == "True")
    share = sum(float(r["model_pcu_h"]) for r in rows) / sum(float(r["observed_pcu_h"]) for r in rows)
    return n_pass, len(rows), share


