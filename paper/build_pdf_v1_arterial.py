        "the largest effect of any intervention tested. A direct test of whether this "
        "combined effect is super additive finds that it is not, a correction to an earlier "
        "working assumption reported here rather than carried forward uncorrected. A separate "
        "robustness check across a range of per-lane road capacities, since this study's own "
        "capacity assumption was never measured against the city, finds the combined lever "
        "lowers delay in direction at every capacity tested while completing more trips, "
        "whereas the individual levers' effects are not robust below the calibrated default, "
        "meaning the standalone findings should be read as conditional on that assumption and "
        "the combined result as this paper's more robust claim. This result is presented alongside the honest limits of the model "
