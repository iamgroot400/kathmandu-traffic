def add_page_furniture(canvas, doc):
    canvas.saveState()
    canvas.setFont("Times-Roman", 8.5)
    canvas.drawCentredString(A4[0] / 2, 0.45 * inch, str(doc.page))
    canvas.restoreState()


def fig(name, caption, width):
    img = Image(str(FIGDIR / name))
    iw, ih = img.imageWidth, img.imageHeight
    img.drawWidth = width
    img.drawHeight = width * ih / iw
    return KeepTogether([img, Paragraph(caption, CAPTION)])


