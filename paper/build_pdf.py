def build_templates():
    top_frame = Frame(MARGIN, BODY_TOP, PAGE_W - 2 * MARGIN, TOP_H,
                      id="top", leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=6)
    left1 = Frame(MARGIN, MARGIN, COL_W, BODY_TOP - MARGIN,
                  id="left1", leftPadding=0, rightPadding=8, topPadding=0, bottomPadding=0)
    right1 = Frame(MARGIN + COL_W + GUTTER, MARGIN, COL_W, BODY_TOP - MARGIN,
                   id="right1", leftPadding=8, rightPadding=0, topPadding=0, bottomPadding=0)
    left = Frame(MARGIN, MARGIN, COL_W, PAGE_H - 2 * MARGIN,
                id="left", leftPadding=0, rightPadding=8, topPadding=0, bottomPadding=0)
    right = Frame(MARGIN + COL_W + GUTTER, MARGIN, COL_W, PAGE_H - 2 * MARGIN,
                 id="right", leftPadding=8, rightPadding=0, topPadding=0, bottomPadding=0)
    page1 = PageTemplate(id="Page1", frames=[top_frame, left1, right1], onPage=add_page_furniture)
    twocol = PageTemplate(id="TwoCol", frames=[left, right], onPage=add_page_furniture)
    return [page1, twocol]


